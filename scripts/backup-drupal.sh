#!/usr/bin/env bash
# Create a verified, checksummed backup of a Drupal site: database, public files,
# optional private files, and a manifest (Git commit, versions, enabled modules).
#
# Usage: scripts/backup-drupal.sh [options]
#   -o, --output DIR        backup directory (default: ../backups/<UTC timestamp>)
#   --docroot DIR           Drupal docroot relative to project root (default: web)
#   --private-dir DIR       host path of private files to archive
#   --skip-files            database and manifest only
#   --lean                  dump structure only for cache/session/watchdog tables
#   --allow-in-repo         permit an output dir inside a Git work tree (not recommended)
#
# Run from the project root. Drush is auto-detected; override with DRUSH="ddev drush".
# Pantheon environments should use: terminus backup:create SITE.ENV --element=all
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"

OUT="../backups/$(date -u +%Y%m%dT%H%M%SZ)"
DOCROOT="web"
PRIVATE_DIR=""
SKIP_FILES=0
LEAN=0
ALLOW_IN_REPO=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    -o|--output) OUT="${2:?missing value}"; shift 2 ;;
    --docroot) DOCROOT="${2:?missing value}"; shift 2 ;;
    --private-dir) PRIVATE_DIR="${2:?missing value}"; shift 2 ;;
    --skip-files) SKIP_FILES=1; shift ;;
    --lean) LEAN=1; shift ;;
    --allow-in-repo) ALLOW_IN_REPO=1; shift ;;
    -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
    *) die "Unknown option: $1" ;;
  esac
done

resolve_drush
[[ "${DRUSH_CMD[0]}" == "terminus" ]] && die "Use 'terminus backup:create' for Pantheon environments."

umask 077
mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"
if [[ "$ALLOW_IN_REPO" -eq 0 ]] && git -C "$OUT" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  die "$OUT is inside a Git work tree. Backups must never be committed. Choose another --output."
fi

section "Preflight"
version="$(drush_quiet status --field=drupal-version)"
[[ -n "$version" ]] || die "Drush could not bootstrap Drupal. Check DRUSH and database access."
pass "Drupal $version reachable via: ${DRUSH_CMD[*]}"
info "Writing to $OUT"

section "Manifest"
{
  echo "created_utc: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "host: $(hostname)"
  echo "project_dir: $(pwd)"
  echo "drupal_version: $version"
  echo "php_version: $(drush_quiet status --field=php-version)"
  echo "db_driver: $(drush_quiet status --field=db-driver)"
  if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    echo "git_commit: $(git rev-parse HEAD)"
    echo "git_branch: $(git rev-parse --abbrev-ref HEAD)"
    if [[ -n "$(git status --porcelain)" ]]; then echo "git_dirty: yes"; else echo "git_dirty: no"; fi
  fi
  if [[ -f composer.lock ]]; then
    echo "composer_lock_sha256: $(sha256_file composer.lock | cut -d' ' -f1)"
  fi
} > "$OUT/manifest.txt"
drush_quiet status > "$OUT/drush-status.txt"
drush_quiet pm:list --status=enabled --format=table > "$OUT/enabled-extensions.txt"
pass "manifest.txt, drush-status.txt, enabled-extensions.txt"

section "Database"
dump_args=(sql:dump)
[[ "$LEAN" -eq 1 ]] && dump_args+=(--structure-tables-key=common)
run_drush "${dump_args[@]}" | gzip -c > "$OUT/database.sql.gz"
gzip -t "$OUT/database.sql.gz" || die "database.sql.gz failed gzip integrity test"
if zgrep -m1 -q 'CREATE TABLE' "$OUT/database.sql.gz"; then
  pass "database.sql.gz ($(du -h "$OUT/database.sql.gz" | awk '{print $1}'))"
else
  fail "database.sql.gz contains no CREATE TABLE statements; inspect it"
fi

if [[ "$SKIP_FILES" -eq 0 ]]; then
  section "Files"
  public_rel="$(drush_quiet status --field=files)"
  public_dir="$DOCROOT/${public_rel:-sites/default/files}"
  if [[ -d "$public_dir" ]]; then
    # Aggregated CSS/JS, compiled Twig and image-style derivatives are regenerated by Drupal.
    tar -czf "$OUT/public-files.tar.gz" -C "$public_dir" \
      --exclude='./css' --exclude='./js' --exclude='./php' --exclude='./styles' .
    tar -tzf "$OUT/public-files.tar.gz" >/dev/null
    pass "public-files.tar.gz from $public_dir ($(du -h "$OUT/public-files.tar.gz" | awk '{print $1}'))"
  else
    warn "Public files directory not found at $public_dir (use --docroot)"
  fi

  if [[ -z "$PRIVATE_DIR" ]]; then
    reported="$(drush_quiet status --field=private)"
    if [[ -n "$reported" && -d "$reported" ]]; then
      PRIVATE_DIR="$reported"
    elif [[ -n "$reported" ]]; then
      warn "Drupal reports private path '$reported' which is not visible on this host; pass --private-dir"
    fi
  fi
  if [[ -n "$PRIVATE_DIR" ]]; then
    [[ -d "$PRIVATE_DIR" ]] || die "--private-dir $PRIVATE_DIR does not exist"
    tar -czf "$OUT/private-files.tar.gz" -C "$PRIVATE_DIR" .
    tar -tzf "$OUT/private-files.tar.gz" >/dev/null
    pass "private-files.tar.gz from $PRIVATE_DIR"
  else
    info "No private files directory configured or found"
  fi
fi

section "Checksums"
( cd "$OUT" && for f in *.gz; do sha256_file "$f"; done > SHA256SUMS )
pass "SHA256SUMS written"
cat "$OUT/SHA256SUMS"

printf '\nNext: test a restore of this backup (docs/02-backup-local-setup.md, Step 6) before relying on it.\n'
summary
